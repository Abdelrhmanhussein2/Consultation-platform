export function getScaledData(period) {
  const d = JSON.parse(JSON.stringify(weekData));
  const p = periodProfiles[period] || periodProfiles.week;

  d.kpis = p.kpis.map(x => [...x]);
  d.ai = [...p.ai];
  d.labels = [...p.labels];
  d.aiTotal = d.ai.reduce((a, b) => a + b, 0).toLocaleString('en-US');
  d.aiGrowth = p.growth;

  const totalUsers = parseInt(d.kpis[5][1].replace(/,/g, ''), 10) || 3487;
  const weightSum = p.cityFactor.reduce((a, b) => a + b, 0);
  d.cities = weekData.cities.map((c, i) => {
    const val = Math.round(totalUsers * (p.cityFactor[i] / weightSum));
    return [c[0], val, (val / totalUsers * 100).toFixed(1) + '%'];
  });

  d.income = d.income.map((x, i) => {
    const pct = p.incomePct[i];
    return [x[0], pct, Math.round(p.incomeTotal * pct / 100), x[3]];
  });
  d.incomeTotal = p.incomeTotal.toLocaleString('en-US');

  return d;
}

export function niceAxisMax(v) {
  if (v <= 100) return Math.ceil(v / 20) * 20;
  if (v <= 500) return Math.ceil(v / 100) * 100;
  if (v <= 2500) return Math.ceil(v / 500) * 500;
  if (v <= 10000) return Math.ceil(v / 2000) * 2000;
  return Math.ceil(v / 5000) * 5000;
}

export function axisFmt(v) {
  if (v >= 1000000) return (v / 1000000).toFixed(v % 1000000 ? 1 : 0) + 'M';
  if (v >= 1000) return (v / 1000).toFixed(v % 1000 ? 1 : 0) + 'K';
  return String(v);
}

export function smoothPath(points) {
  if (!points || !points.length) return '';
  if (points.length === 1) return `M${points[0][0]},${points[0][1]}`;
  let d = `M${points[0][0]},${points[0][1]}`;
  for (let i = 0; i < points.length - 1; i++) {
    const p0 = points[i - 1] || points[i];
    const p1 = points[i];
    const p2 = points[i + 1];
    const p3 = points[i + 2] || p2;
    const cp1x = p1[0] + (p2[0] - p0[0]) / 6;
    const cp1y = p1[1] + (p2[1] - p0[1]) / 6;
    const cp2x = p2[0] - (p3[0] - p1[0]) / 6;
    const cp2y = p2[1] - (p3[1] - p1[1]) / 6;
    d += ` C${cp1x},${cp1y} ${cp2x},${cp2y} ${p2[0]},${p2[1]}`;
  }
  return d;
}

export function daysBetween(a, b) {
  const da = new Date(a + 'T00:00:00');
  const db = new Date(b + 'T00:00:00');
  return Math.max(1, Math.round((db - da) / 86400000) + 1);
}

export function profileForRange(days) {
  if (days <= 1) return 'day';
  if (days <= 10) return 'week';
  if (days <= 45) return 'month';
  if (days <= 120) return 'quarter';
  if (days <= 240) return 'half';
  return 'year';
}

